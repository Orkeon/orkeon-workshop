import { DomainError } from './errors.js';
import type { CrewKind } from './mounts/launchers.js';

/**
 * A team the bench runs: a crew `orkeon run` starts (YAML or TypeScript), or a team hosted by a C#
 * program of its own — `host/`, as `OrkeonCrewHost/new-team.sh` writes it (skill
 * `orkeon-crew-csharp`) — which loads a YAML crew from `crew/` or builds its crew in code.
 */
export type TeamKind = CrewKind | 'csharp';

/** The folder of a team that holds its C# host: a solution or a project makes the team a C# one. */
export const HOST_FOLDER = 'host';

/** The configuration the host is built and run in: what its launchers run. */
export const HOST_CONFIGURATION = 'Release';

/**
 * Whether a `host/` is the host of a C# team, in the shape `new-team.sh` writes: a solution
 * (`*.sln`, `*.slnx`) at its root, or a project `src/<Name>.Host/<Name>.Host.csproj` (`hostProjects`,
 * the `<Name>.Host` folders that hold one). Any other project — a folder of an older YAML team
 * mounted as `host/` — makes no C# team.
 */
export function isHostFolder(entries: readonly string[], hostProjects: readonly string[] = []): boolean {
  return hostProjects.length > 0 || entries.some((name) => /\.(sln|slnx)$/i.test(name));
}

/**
 * The settings the host reads, as one document: `documents` lowest precedence first (the team
 * folder's `appsettings.json`, its `appsettings.local.json`, `settings/<slug>/appsettings.json`),
 * merged the way .NET configuration merges JSON files — a later value wins, objects merge key by key
 * whatever the case of a key, arrays index by index. A document that is no object is skipped.
 */
export function mergeHostSettings(documents: readonly unknown[]): Record<string, unknown> | null {
  let merged: Record<string, unknown> | null = null;
  for (const document of documents) {
    if (isObject(document)) {
      merged = mergeValue(merged ?? {}, document) as Record<string, unknown>;
    }
  }
  return merged;
}

function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function mergeValue(base: unknown, over: unknown): unknown {
  if (Array.isArray(base) && Array.isArray(over)) {
    return base.length > over.length ? over.map((item, index) => mergeValue(base[index], item)).concat(base.slice(over.length)) : over.map((item, index) => mergeValue(base[index], item));
  }
  if (!isObject(base) || !isObject(over)) {
    return over;
  }
  const result: Record<string, unknown> = { ...base };
  for (const [key, value] of Object.entries(over)) {
    const existing = Object.keys(result).find((name) => name.toLowerCase() === key.toLowerCase());
    if (existing === undefined) {
      result[key] = value;
    } else {
      result[existing] = mergeValue(result[existing], value);
    }
  }
  return result;
}

/**
 * The host project, relative to `host/`: the one folder `src/<Name>.Host/` that holds
 * `<Name>.Host.csproj`, as `new-team.sh` names it. None, or more than one, is refused.
 */
export function hostProjectOf(hostFolder: string, candidates: readonly string[]): string {
  if (candidates.length === 1) {
    return `src/${candidates[0] as string}`;
  }
  throw new DomainError(
    candidates.length === 0
      ? `${hostFolder} holds no src/<Name>.Host/<Name>.Host.csproj: the host of a C# team is generated by OrkeonCrewHost/new-team.sh (skill orkeon-crew-csharp)`
      : `${hostFolder} holds several host projects (${candidates.map((name) => `src/${name}`).join(', ')}): a C# team has one`,
  );
}

/**
 * `dotnet run` of the host on the team folder, from `host/` (its `global.json` and `nuget.config`
 * apply), as `run.sh` runs it — without the build, which L0 has done: what the build would print
 * on stdout would mix with the event stream.
 */
export function hostRunArguments(project: string, teamFolder: string, hostArguments: readonly string[]): string[] {
  return ['run', '--project', project, '-c', HOST_CONFIGURATION, '--no-build', '--', '--team-dir', teamFolder, ...hostArguments];
}

/**
 * What the launchers `new-team.sh` writes lack: `run.sh` and `run.cmd` run the host project on
 * the team folder. A Studio card (`team.json`, or the `studio-team.json` Studio still adopts) is refused: Studio would launch `crew/` with the stock `orkeon`,
 * without the host's tools and wiring.
 */
export function hostLauncherProblems(project: string, runSh: string | null, runCmd: string | null, studioCard: boolean): string[] {
  const problems: string[] = [];
  const expect = (file: string, text: string | null, command: string): void => {
    if (text === null) {
      problems.push(`${file} is missing`);
    } else if (!text.includes(command) || !text.includes('--team-dir')) {
      problems.push(`${file} does not run ${command} … --team-dir <the team folder>`);
    }
  };
  expect('run.sh', runSh, `dotnet run --project ${project}`);
  expect('run.cmd', runCmd, `dotnet run --project ${project.replaceAll('/', '\\')}`);
  if (studioCard) {
    problems.push('a Studio card (team.json) exists: Orkeon Studio would launch crew/ with the stock orkeon, without the host — a C# team has no Studio card');
  }
  return problems;
}

/** The counts of the summary `dotnet test` prints (`total: N`, `failed: N`, `succeeded: N`), summed over the test runs; null without one. */
export function dotnetTestSummary(output: string): { total: number; failed: number; passed: number } | null {
  const sum = (label: string): number | null => {
    const found = [...output.matchAll(new RegExp(`^\\s*${label}:\\s*(\\d+)\\s*$`, 'gm'))];
    return found.length === 0 ? null : found.reduce((total, match) => total + Number(match[1]), 0);
  };
  const total = sum('total');
  if (total === null) {
    return null;
  }
  return { total, failed: sum('failed') ?? 0, passed: sum('succeeded') ?? 0 };
}

/** `dotnet publish` of the host project, from `host/`, into `output`: what a deployment of a C# team carries. */
export function hostPublishArguments(project: string, output: string): string[] {
  return ['publish', project, '-c', HOST_CONFIGURATION, '-o', output];
}

/**
 * The launchers of a deployed C# team: they run the host published under `host/publish/` on the
 * team folder with `dotnet <Name>.Host.dll` — the .NET runtime alone, no SDK, no package feed, no
 * network. The host still reads `settings/<slug>/appsettings.json` two levels above the team folder.
 */
export function publishedLaunchers(project: string): { runSh: string; runCmd: string } {
  const assembly = `${project.split('/').pop() as string}.dll`;
  return {
    runSh: [
      // POSIX sh, as the YAML and TypeScript launchers (`sh run.sh` works as `./run.sh` does):
      // the folder is the script's own, a symbolic link to it followed.
      '#!/usr/bin/env sh',
      '# The C# host of the team, published by orkeon-bench deploy: needs the .NET runtime of the host (dotnet --list-runtimes).',
      'set -eu',
      'SELF="$0"',
      'while [ -L "$SELF" ]; do',
      '  LINK="$(readlink "$SELF")"',
      '  case "$LINK" in',
      '    /*) SELF="$LINK" ;;',
      '    *) SELF="$(dirname "$SELF")/$LINK" ;;',
      '  esac',
      'done',
      'DIR="$(cd "$(dirname "$SELF")" && pwd)"',
      `exec dotnet "$DIR/host/publish/${assembly}" --team-dir "$DIR" "$@"`,
      '',
    ].join('\n'),
    runCmd: [
      '@echo off',
      'rem The C# host of the team, published by orkeon-bench deploy: needs the .NET runtime of the host (dotnet --list-runtimes).',
      'setlocal',
      'set "DIR=%~dp0"',
      'if "%DIR:~-1%"=="\\" set "DIR=%DIR:~0,-1%"',
      `dotnet "%DIR%\\host\\publish\\${assembly}" --team-dir "%DIR%" %*`,
      '',
    ].join('\r\n'),
  };
}
